CREATE TABLE historico_agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id BIGINT NOT NULL REFERENCES agendamentos(id),
    tipo_evento VARCHAR(30) NOT NULL,
    registrado_em TIMESTAMP(6) NOT NULL,
    usuario_id BIGINT,
    usuario_email VARCHAR(255),
    perfil_usuario VARCHAR(30),
    cliente_id BIGINT,
    cliente_nome VARCHAR(255) NOT NULL,
    barbeiro_id BIGINT NOT NULL,
    barbeiro_nome VARCHAR(255) NOT NULL,
    servico_id BIGINT NOT NULL,
    servico_nome VARCHAR(255) NOT NULL,
    valor_servico DECIMAL(12,2),
    servico_adicional_id BIGINT,
    servico_adicional_nome VARCHAR(255),
    valor_servico_adicional DECIMAL(12,2),
    data_hora_anterior TIMESTAMP(6),
    data_hora_nova TIMESTAMP(6),
    forma_pagamento VARCHAR(20),
    valor_total_comanda DECIMAL(12,2)
);

CREATE INDEX idx_historico_agendamento_data ON historico_agendamentos(agendamento_id, registrado_em);

INSERT INTO historico_agendamentos (
    agendamento_id, tipo_evento, registrado_em, cliente_id, cliente_nome,
    barbeiro_id, barbeiro_nome, servico_id, servico_nome, valor_servico,
    servico_adicional_id, servico_adicional_nome, valor_servico_adicional,
    data_hora_nova, forma_pagamento, valor_total_comanda
)
SELECT a.id,
       CASE
           WHEN a.status_agendamento = 'CONCLUIDO' THEN 'CONCLUIDO'
           WHEN a.status_agendamento IN ('CANCELADO_CLIENTE', 'CANCELADO_BARBEIRO') THEN 'CANCELADO'
           ELSE 'NAO_COMPARECEU'
       END,
       COALESCE(a.atualizado_em, a.criado_em),
       a.cliente_id,
       COALESCE(c.nome, a.cliente_avulso_nome),
       a.barbeiro_id,
       b.nome,
       a.servico_id,
       s.nome,
       s.preco::numeric(12,2),
       adicional.servico_id,
       adicional.servico_nome,
       adicional.valor_servico,
       a.data_hora_inicio,
       a.forma_pagamento,
       CASE WHEN a.status_agendamento = 'CONCLUIDO'
            THEN COALESCE(a.valor_total_comanda,
                          (SELECT SUM(cm.valor_servico) FROM comissoes cm WHERE cm.agendamento_id = a.id))
            ELSE NULL
       END
FROM agendamentos a
LEFT JOIN clientes c ON c.id = a.cliente_id
JOIN barbeiros b ON b.id = a.barbeiro_id
JOIN servicos s ON s.id = a.servico_id
LEFT JOIN LATERAL (
    SELECT cm.servico_id, cm.servico_nome, cm.valor_servico
    FROM comissoes cm
    WHERE cm.agendamento_id = a.id AND cm.servico_id <> a.servico_id
    ORDER BY cm.id
    LIMIT 1
) adicional ON TRUE
WHERE a.status_agendamento IN ('CONCLUIDO', 'CANCELADO_CLIENTE', 'CANCELADO_BARBEIRO', 'NAO_COMPARECEU');
