CREATE TABLE administrador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    telefone VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    nivel_acesso VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL
);

CREATE TABLE barbearia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_fantasia VARCHAR(150) NOT NULL,
    razao_social VARCHAR(150) NOT NULL,
    cnpj VARCHAR(14) NOT NULL UNIQUE,
    telefone VARCHAR(11) NOT NULL UNIQUE,
    whatsapp VARCHAR(11) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    endereco VARCHAR(150) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    cep VARCHAR(8) NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    logo_url VARCHAR(2048)
);

CREATE TABLE barbeiros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    data_nascimento DATE NOT NULL,
    telefone VARCHAR(255) NOT NULL UNIQUE,
    especialidade VARCHAR(255) NOT NULL,
    foto_url VARCHAR(2048),
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    nivel_acesso VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL
);

CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    data_nascimento DATE NOT NULL,
    telefone VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    nivel_acesso VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    canal_notificacao VARCHAR(20),
    notificacoes_autorizadas BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL UNIQUE,
    descricao VARCHAR(255) NOT NULL,
    categoria VARCHAR(255) NOT NULL,
    preco DOUBLE PRECISION NOT NULL,
    porcentagem_barbearia DECIMAL(5,2) NOT NULL DEFAULT 50.00,
    duracao_em_minutos INTEGER NOT NULL,
    status VARCHAR(255) NOT NULL
);

CREATE TABLE horario_funcionamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbearia_id BIGINT NOT NULL REFERENCES barbearia(id),
    dia_semana VARCHAR(255),
    horario_inicio TIME,
    horario_fim TIME
);

CREATE TABLE bloqueio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbeiro_id BIGINT NOT NULL REFERENCES barbeiros(id),
    data_inicio TIMESTAMP(6) NOT NULL,
    data_fim TIMESTAMP(6) NOT NULL,
    motivo VARCHAR(255) NOT NULL
);

CREATE TABLE agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    barbeiro_id BIGINT NOT NULL REFERENCES barbeiros(id),
    servico_id BIGINT NOT NULL REFERENCES servicos(id),
    data_hora_inicio TIMESTAMP(6) NOT NULL,
    data_hora_fim TIMESTAMP(6) NOT NULL,
    status_agendamento VARCHAR(255) NOT NULL,
    observacao VARCHAR(500),
    criado_em TIMESTAMP(6) NOT NULL,
    atualizado_em TIMESTAMP(6)
);

CREATE TABLE comissoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id BIGINT NOT NULL,
    barbeiro_id BIGINT NOT NULL,
    barbeiro_nome VARCHAR(150) NOT NULL,
    servico_id BIGINT NOT NULL,
    servico_nome VARCHAR(150) NOT NULL,
    data_conclusao DATE NOT NULL,
    concluido_em TIMESTAMP(6) NOT NULL,
    valor_servico DECIMAL(12,2) NOT NULL,
    porcentagem_barbearia DECIMAL(5,2) NOT NULL,
    porcentagem_barbeiro DECIMAL(5,2) NOT NULL,
    valor_barbearia DECIMAL(12,2) NOT NULL,
    valor_barbeiro DECIMAL(12,2) NOT NULL,
    CONSTRAINT uk_comissao_agendamento UNIQUE (agendamento_id)
);

CREATE TABLE notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    agendamento_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    canal VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    chave_idempotencia VARCHAR(180) NOT NULL,
    destinatario VARCHAR(254),
    nome_cliente VARCHAR(150) NOT NULL,
    nome_barbearia VARCHAR(150) NOT NULL,
    nome_servico VARCHAR(150) NOT NULL,
    nome_barbeiro VARCHAR(150) NOT NULL,
    data_hora_agendamento TIMESTAMP(6) NOT NULL,
    programada_para TIMESTAMP(6) NOT NULL,
    criada_em TIMESTAMP(6) NOT NULL,
    tentada_em TIMESTAMP(6),
    enviada_em TIMESTAMP(6),
    proxima_tentativa_em TIMESTAMP(6),
    quantidade_tentativas INTEGER NOT NULL,
    codigo_provedor VARCHAR(200),
    erro_seguro VARCHAR(500),
    CONSTRAINT uk_notificacao_idempotencia UNIQUE (chave_idempotencia)
);

CREATE TABLE recuperacoes_senha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    usuario_id BIGINT NOT NULL,
    nivel_acesso VARCHAR(30) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expira_em TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_barbeiro_data ON agendamentos (barbeiro_id, data_hora_inicio);
CREATE INDEX idx_cliente ON agendamentos (cliente_id);
CREATE INDEX idx_status_data ON agendamentos (status_agendamento, data_hora_inicio);
CREATE INDEX idx_comissao_data_barbeiro ON comissoes (data_conclusao, barbeiro_id);
CREATE INDEX idx_notificacao_fila ON notificacoes (status, programada_para);
CREATE INDEX idx_recuperacao_email ON recuperacoes_senha (email);
